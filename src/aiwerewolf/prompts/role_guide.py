"""Role-specific action tendencies — soft hints, not hard scripts."""

from __future__ import annotations

from schema.enums import Role

_ROLE_GUIDES: dict[Role, str] = {
    Role.WOLF: """\
- 狼队通常只需 **1 人** 在白天悍跳预言家（若已有队友跳则你不要再跳）。
- 其余狼可深水、冲锋号票或倒钩，视场上已有几人对跳、票型与队友发言而定。
- 夜晚与队友商议时：说明刀口理由、白天分工（谁跳、谁藏、是否倒钩），可提出不同意见。
- 不要四人同质化「全员悍跳」；game_guide 中的狼战术是选项库，不是每局必做。""",
    Role.SEER: """\
- 真预言家常见做法是上警报验人，但也可根据位置、是否已有对跳、自身存活风险选择藏或晚跳。
- 若场上已有 2+ 人自称预言家，先判断谁更像狼再决定是否强势报验。
- 警徽流可简可繁，关键是让可信好人能跟上你的逻辑。""",
    Role.WITCH: """\
- 首夜是否用解药、是否公开银水，取决于刀口位置与场上发言，**不必**首夜必救或首夜必跳女巫。
- 毒药留给高置信狼或乱局时的明狼；避免为「像攻略」而盲毒。
- 隐藏身份往往比首日高调更有价值。""",
    Role.HUNTER: """\
- 默认隐藏猎人身份；被点杀、场上有假猎人或局势混乱时再考虑跳明。
- 发言不必强势刚硬，可装晕装民引狼刀（挡刀）。""",
    Role.IDIOT: """\
- 多数时候隐匿白痴身份；被狼查杀时可故意聊差引扛推后翻牌。
- 不必主动报神职。""",
    Role.VILLAGER: """\
- 村民无技能，**不要**自报「我是村民/好人」式空身份（除非在认真表水）。
- 可穿神衣挡刀但需有理由；重点是站边、盘逻辑、看票型，而非模仿神职发言模板。""",
}


def build_role_action_guide(role: Role) -> str:
    return _ROLE_GUIDES.get(role, "- 根据局势灵活行动。")
